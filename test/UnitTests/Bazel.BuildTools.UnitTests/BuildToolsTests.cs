    [TestMethod]
    [DataRow(false, DisplayName = "Resx preserves LF")]
    [DataRow(true, DisplayName = "Resx preserves CRLF")]
    public async Task Resx_PreservesTextAndEmitsBom(bool crlf)
    {
        string newline = crlf ? "\r\n" : "\n";
        string input = Write("input.resx", """
            <root>
              <data name="Empty"><value></value></data>
              <data name="Multiline"><value>first &amp; second
            last "quoted"</value></data>
              <data name="Whitespace" xml:space="preserve"><value>  </value></data>
            </root>
            """.ReplaceLineEndings(newline));
        string resources = PathFor("Fixture.Resources.resources");
        string source = PathFor("Resources.g.cs");

        (int exitCode, string output) = await RunAsync("resx", input, "Fixture.Resources", resources, source);

        Assert.AreEqual(0, exitCode, output);
        Dictionary<string, string> values = ReadResources(resources);
        Assert.AreEqual(3, values.Count);
        Assert.AreEqual(string.Empty, values["Empty"]);
        Assert.AreEqual("  ", values["Whitespace"]);
        Assert.AreEqual("""
            first & second
            last "quoted"
            """.ReplaceLineEndings(newline), values["Multiline"]);
        CollectionAssert.AreEqual(new byte[] { 0xEF, 0xBB, 0xBF }, File.ReadAllBytes(source)[..3]);
        Assert.AreEqual("""
            // <auto-generated/>
            #nullable enable
            namespace Fixture;
            internal static partial class Resources
            {
                internal static global::System.Resources.ResourceManager ResourceManager { get; } = new("Fixture.Resources", typeof(Resources).Assembly);
                internal static global::System.Globalization.CultureInfo? Culture { get; set; }
                internal static string GetResourceString(string key) => ResourceManager.GetString(key, Culture)!;
                internal static string @Empty => GetResourceString("Empty");
                internal static string @Multiline => GetResourceString("Multiline");
                internal static string @Whitespace => GetResourceString("Whitespace");
            }

            """.ReplaceLineEndings(), File.ReadAllText(source).ReplaceLineEndings());
    }

    [TestMethod]
    public async Task Xlf_AppliesTargetsAndPreservesMissingTargetFallback()
    {
        string neutral = Write("input.resx", """
            <root>
              <data name="Translated"><value>Hello</value></data>
              <data name="Missing"><value>Fallback</value></data>
              <data name="Empty"><value>Not empty</value></data>
              <data name="Unfinished"><value>Original</value></data>
            </root>
            """);
        string catalog = Write("input.fr.xlf", """
            <xliff xmlns="urn:oasis:names:tc:xliff:document:1.2" version="1.2">
              <file target-language="fr"><body><group id="strings">
                <trans-unit id="Translated"><source>Hello</source><target state="translated">Bonjour</target></trans-unit>
                <trans-unit id="Missing"><source>Fallback</source></trans-unit>
                <trans-unit id="Empty"><source>Not empty</source><target state="new"></target></trans-unit>
                <trans-unit id="Unfinished"><source>Original</source><target state="needs-review-translation">Draft</target></trans-unit>
              </group></body></file>
            </xliff>
            """);
        string resources = PathFor("Fixture.Resources.fr.resources");

        (int exitCode, string output) = await RunAsync("xlf", neutral, catalog, "fr", resources);

        Assert.AreEqual(0, exitCode, output);
        Dictionary<string, string> values = ReadResources(resources);
        Assert.AreEqual(4, values.Count);
        Assert.AreEqual("Bonjour", values["Translated"]);
        Assert.AreEqual("Fallback", values["Missing"]);
        Assert.AreEqual(string.Empty, values["Empty"]);
        Assert.AreEqual("Draft", values["Unfinished"]);
    }

    [TestMethod]
    [DataRow("culture", "Catalog culture does not match")]
    [DataRow("stale", "Duplicate, unknown, or stale translation")]
    [DataRow("duplicate", "Duplicate, unknown, or stale translation")]
    [DataRow("inline", "Inline XLIFF codes require explicit rendering")]
    public async Task Xlf_RejectsInvalidCatalog(string scenario, string expectedError)
    {
        string neutral = Write("input.resx", "<root><data name=\"Text\"><value>Hello</value></data></root>");
        string unit = scenario switch
        {
            "stale" => "<trans-unit id=\"Text\"><source>Old</source><target>Bonjour</target></trans-unit>",
            "inline" => "<trans-unit id=\"Text\"><source>Hello</source><target><g id=\"1\">Bonjour</g></target></trans-unit>",
            _ => "<trans-unit id=\"Text\"><source>Hello</source><target>Bonjour</target></trans-unit>",
        };
        string language = scenario == "culture" ? "de" : "fr";
        string units = scenario == "duplicate" ? unit + unit : unit;
        string catalog = Write("input.fr.xlf", $"""
            <xliff xmlns="urn:oasis:names:tc:xliff:document:1.2" version="1.2">
              <file target-language="{language}"><body>{units}</body></file>
            </xliff>
            """);
        string resources = PathFor("output.resources");

        (int exitCode, string output) = await RunAsync("xlf", neutral, catalog, "fr", resources);

        Assert.AreNotEqual(0, exitCode);
        Assert.Contains(expectedError, output);
        Assert.IsFalse(File.Exists(resources));
    }

    [TestMethod]
    public async Task Resx_RejectsNonStringDataBeforeWritingOutputs()
    {
        string input = Write("input.resx", """
            <root><data name="Number" type="System.Int32"><value>42</value></data></root>
            """);
        string resources = PathFor("output.resources");
        string source = PathFor("output.cs");

        (int exitCode, string output) = await RunAsync("resx", input, "Fixture.Resources", resources, source);

        Assert.AreNotEqual(0, exitCode);
        Assert.Contains("Only string resources are supported", output);
        Assert.IsFalse(File.Exists(resources));
        Assert.IsFalse(File.Exists(source));
    }

    [TestMethod]
    public async Task Metadata_UsesVersionTemplateAndBuildStamp()
    {
        string versions = Write("Versions.props", "<Project><PropertyGroup><VersionPrefix>7.8.9</VersionPrefix></PropertyGroup></Project>");
        string template = Write("BuildInfo.cs.template", "internal static class BuildInfo { internal const string Version = \"${Version}\"; }");
        string stamp = Write("status.txt", "BUILD_TIMESTAMP 0");
        string metadata = PathFor("AssemblyInfo.g.cs");
        string buildInfo = PathFor("BuildInfo.g.cs");

        (int exitCode, string output) = await RunAsync("metadata", versions, "VersionPrefix", metadata, template, buildInfo, "-", "-", "-", "14.0.0.0", stamp);

        Assert.AreEqual(0, exitCode, output);
        Assert.AreEqual("""
            // <auto-generated/>
            [assembly: global::System.Reflection.AssemblyVersion("14.0.0.0")]
            [assembly: global::System.Reflection.AssemblyFileVersion("7.8.9.0")]
            [assembly: global::System.Reflection.AssemblyInformationalVersion("7.8.9-bazel")]
            [assembly: global::System.Reflection.AssemblyMetadata("TestFx.BuildSystem", "Bazel")]
            [assembly: global::System.Resources.NeutralResourcesLanguage("en")]
            [assembly: global::System.Reflection.AssemblyMetadata("Microsoft.Testing.Platform.Application.BuildTimeUTC", "1970/01/01")]

            """.ReplaceLineEndings(), File.ReadAllText(metadata).ReplaceLineEndings());
        Assert.AreEqual("internal static class BuildInfo { internal const string Version = \"7.8.9-bazel\"; }", File.ReadAllText(buildInfo));
        CollectionAssert.AreEqual(new byte[] { 0xEF, 0xBB, 0xBF }, File.ReadAllBytes(buildInfo)[..3]);
    }

    [TestMethod]
    [DataRow("VersionPrefix", "4.6.0-bazel")]
    [DataRow("TestingPlatformVersionPrefix", "2.6.0-bazel")]
    public async Task PackageVersion_SelectsProductAndMarksExperimentalBuild(string property, string expected)
    {
        string versions = Write("Versions.props", """
            <Project><PropertyGroup>
              <VersionPrefix>4.6.0</VersionPrefix>
              <TestingPlatformVersionPrefix>2.6.0</TestingPlatformVersionPrefix>
            </PropertyGroup></Project>
            """);
        string versionFile = PathFor("version.txt");

        (int exitCode, string output) = await RunAsync("version", versions, property, versionFile);

        Assert.AreEqual(0, exitCode, output);
        Assert.AreEqual(expected, File.ReadAllText(versionFile));
    }

    [TestMethod]
    [DataRow("")]
    [DataRow("<VersionPrefix>1.2.3</VersionPrefix><VersionPrefix>4.5.6</VersionPrefix>")]
    public async Task PackageVersion_RejectsMissingOrDuplicateProperty(string properties)
    {
        string versions = Write("Versions.props", $"<Project><PropertyGroup>{properties}</PropertyGroup></Project>");
        string versionFile = PathFor("version.txt");

        (int exitCode, string output) = await RunAsync("version", versions, "VersionPrefix", versionFile);

        Assert.AreNotEqual(0, exitCode);
        Assert.Contains("Expected exactly one VersionPrefix property", output);
        Assert.IsFalse(File.Exists(versionFile));
    }

    private static Dictionary<string, string> ReadResources(string path)
    {
        using var reader = new ResourceReader(path);
        var values = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (DictionaryEntry entry in reader)
        {
            values.Add(Assert.IsInstanceOfType<string>(entry.Key), Assert.IsInstanceOfType<string>(entry.Value));
        }

        return values;
    }

    private string PathFor(string name)
    {
        string? directory = context.TestTempDirectory;
        Assert.IsNotNull(directory);
        return Path.Combine(directory, name);
    }

    private string Write(string name, string text)
    {
        string path = PathFor(name);
        File.WriteAllText(path, text, new UTF8Encoding(encoderShouldEmitUTF8Identifier: true));
        return path;
    }

    private async Task<(int exitCode, string output)> RunAsync(params string[] arguments)
    {
        string location = Environment.GetEnvironmentVariable("TESTFX_BAZEL_BUILD_TOOLS")
            ?? throw new InvalidOperationException("The Bazel build-tool location was not supplied.");
        string tool = global::Bazel.Runfiles.Create().Rlocation(location);
        using var process = new Process
        {
            StartInfo = new ProcessStartInfo(Environment.ProcessPath!)
            {
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
            },
        };
        process.StartInfo.ArgumentList.Add("exec");
        process.StartInfo.ArgumentList.Add(tool);
        foreach (string argument in arguments)
        {
            process.StartInfo.ArgumentList.Add(argument);
        }

        Assert.IsTrue(process.Start());
        Task<string> output = process.StandardOutput.ReadToEndAsync();
        Task<string> error = process.StandardError.ReadToEndAsync();
        using var timeout = CancellationTokenSource.CreateLinkedTokenSource(context.CancellationToken);
        timeout.CancelAfter(TimeSpan.FromSeconds(30));
        try
        {
            await process.WaitForExitAsync(timeout.Token);
        }
        finally
        {
            if (!process.HasExited)
            {
                process.Kill(entireProcessTree: true);
                using var cleanup = new CancellationTokenSource(TimeSpan.FromSeconds(10));
                await process.WaitForExitAsync(cleanup.Token);
            }
        }

        return (process.ExitCode, await output + await error);
    }
}
