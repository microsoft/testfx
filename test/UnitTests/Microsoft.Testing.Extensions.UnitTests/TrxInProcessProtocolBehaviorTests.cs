    [TestMethod]
    public async Task RegisteredLifecycle_CompletedUnicodeReportPublishesExactArtifactAndSweepsOrphan()
    {
        var fixture = new TrxInProcessProtocolFixture(TestContext.CancellationToken);
        try
        {
            await fixture.BindAsync();
            await fixture.ConnectChildAsync();
            await fixture.StartSessionAsync();
            using var rejected = new CancellationTokenSource();
            rejected.Cancel();
            OperationCanceledException consumeCancellation = await Assert.ThrowsExactlyAsync<OperationCanceledException>(
                () => fixture.ChildConsumer.ConsumeAsync(
                    null!, Update(FirstId, "must not appear", PassedTestNodeStateProperty.CachedInstance, "Rejected"), rejected.Token));
            Assert.AreEqual(rejected.Token, consumeCancellation.CancellationToken);
            Assert.IsEmpty(fixture.Memory.Files);
            Assert.IsEmpty(fixture.Memory.Events);

            await fixture.ChildConsumer.ConsumeAsync(
                null!, Update(FirstId, "Réussite 東京 😀", PassedTestNodeStateProperty.CachedInstance, "Réussite", includeOutput: true), fixture.Token);
            await fixture.ChildConsumer.ConsumeAsync(
                null!, Update(SecondId, "Ignoré é", SkippedTestNodeStateProperty.CachedInstance, "Ignoré"), fixture.Token);
            fixture.KeepSidecarOnDelete = true;
            fixture.Memory.Clock.SetupGet(value => value.UtcNow).Returns(TrxBehaviorFixture.Start.AddSeconds(10));
            await fixture.SessionLifetime.OnTestSessionFinishingAsync(fixture.Session);
            await fixture.CloseChildAsync(0);

            string sidecar = fixture.SidecarPath;
            Assert.AreEqual(fixture.ResultsDirectory, Path.GetDirectoryName(sidecar));
            Assert.IsEmpty(fixture.Memory.Publications, "A controller-backed child must send the filename over IPC, not publish a session artifact.");
            Assert.AreSequenceEqual(new[] { sidecar }, fixture.DeleteAttempts);
            Assert.IsTrue(fixture.Memory.Files[sidecar].IsDisposed);
            byte[] writtenReport = fixture.Memory.GetBytes(fixture.ReportPath);
            int fileCalls = fixture.Memory.FileSystem.Invocations.Count;
            var uninspectedProcess = new Mock<ITestHostProcessInformation>(MockBehavior.Strict);
            OperationCanceledException exitCancellation = await Assert.ThrowsExactlyAsync<OperationCanceledException>(
                () => fixture.Controller.OnTestHostProcessExitedAsync(uninspectedProcess.Object, rejected.Token));
            Assert.AreEqual(rejected.Token, exitCancellation.CancellationToken);
            uninspectedProcess.VerifyNoOtherCalls();
            Assert.HasCount(fileCalls, fixture.Memory.FileSystem.Invocations);
            Assert.IsEmpty(fixture.Memory.Publications);
            Assert.AreSequenceEqual(new[] { sidecar }, fixture.DeleteAttempts);

            fixture.KeepSidecarOnDelete = false;
            await fixture.Controller.OnTestHostProcessExitedAsync(Process(0).Object, fixture.Token);

            AssertControllerArtifact(fixture);
            Assert.AreSequenceEqual(writtenReport, fixture.Memory.GetBytes(fixture.ReportPath), "Completed reports must not be regenerated by the controller.");
            XDocument report = fixture.Report;
            AssertCommonMetadata(fixture, report, TrxBehaviorFixture.Start.AddSeconds(1));
            XElement summary = report.Root!.Element(Ns + "ResultSummary")!;
            Assert.AreEqual("Completed", (string?)summary.Attribute("outcome"));
            AssertCounters(summary, total: 2, executed: 1, passed: 1, failed: 0, timeout: 0, skipped: 1);
            AssertResultMetadata(fixture, report, ["Réussite 東京 😀", "Ignoré é"], ["Passed", "NotExecuted"], ["Réussite", "Ignoré"]);
            Assert.AreEqual("sortie: élève 東京 😀", report.Descendants(Ns + "StdOut").Single().Value);
            Assert.AreEqual("diagnostic: Ω", report.Descendants(Ns + "StdErr").Single().Value);
            Assert.IsEmpty(report.Descendants(Ns + "RunInfo"));
            Assert.IsEmpty(fixture.Memory.Displays);
            Assert.AreSequenceEqual(new[] { sidecar, sidecar }, fixture.DeleteAttempts);
            Assert.IsFalse(fixture.Memory.Files.ContainsKey(sidecar));
            AssertBefore(fixture.Memory.Events, "dispose:" + sidecar, "delete-attempt:" + sidecar);
            AssertBefore(fixture.Memory.Events, "publish", "delete:" + sidecar);
            fixture.Memory.FileSystem.Verify(
                value => value.NewFileStream(sidecar, FileMode.Open, FileAccess.Read, FileShare.ReadWrite), Times.Once);
            fixture.Memory.Capability.Verify(value => value.Enable(), Times.Once);
        }
        finally
        {
            await fixture.CloseAsync();
        }
    }

    [TestMethod]
    [DataRow(false, DisplayName = "TrxProtocol_CrashedWithCorruptTail")]
    [DataRow(true, DisplayName = "TrxProtocol_AbortedWithCorruptTail")]
    public async Task RegisteredLifecycle_InterruptedChildRecoversUnicodePrefixAndControllerArtifact(bool aborted)
    {
        var fixture = new TrxInProcessProtocolFixture(TestContext.CancellationToken);
        try
        {
            await fixture.BindAsync();
            await fixture.ConnectChildAsync();
            await fixture.StartSessionAsync();
            await fixture.ChildConsumer.ConsumeAsync(
                null!, Update(FirstId, "Réussite 東京 😀", PassedTestNodeStateProperty.CachedInstance, "Réussite", includeOutput: true), fixture.Token);
            await fixture.ChildConsumer.ConsumeAsync(
                null!, Update(SecondId, "Délai dépassé Ω", new TimeoutTestNodeStateProperty(), "Expiration"), fixture.Token);

            // Interrupt only the supported child shutdown path, without finishing a session or
            // manufacturing an IPC request. Disposal joins the actual writer before byte inspection.
            await fixture.CloseChildAsync(aborted ? 3 : 17);
            string sidecar = fixture.SidecarPath;
            Assert.AreEqual(fixture.ResultsDirectory, Path.GetDirectoryName(sidecar));
            Assert.IsTrue(fixture.Memory.Files[sidecar].IsDisposed);
            Assert.IsFalse(fixture.Memory.Files.ContainsKey(fixture.ReportPath));
            Assert.IsEmpty(fixture.Memory.Publications);
            Assert.IsEmpty(fixture.DeleteAttempts);
            fixture.AddCorruptTail(sidecar);

            string attachmentPath = Path.Combine(fixture.ResultsDirectory, "controller", "trace-é-東京.bin");
            fixture.Memory.ExistingFiles[attachmentPath] = [0, 0xC3, 0xA9, 0xFF, 42];
            var collector = new Mock<IDataProducer>();
            collector.SetupGet(value => value.Uid).Returns("protocol.collector");
            collector.SetupGet(value => value.Version).Returns("2.3.4");
            collector.SetupGet(value => value.DisplayName).Returns("Collecteur 東京");
            collector.SetupGet(value => value.Description).Returns("Controller-owned evidence");
            await fixture.ControllerConsumer.ConsumeAsync(
                collector.Object, new FileArtifact(new FileInfo(attachmentPath), "trace", "controller evidence"), fixture.Token);
            fixture.Memory.Clock.SetupGet(value => value.UtcNow).Returns(TrxBehaviorFixture.Start.AddSeconds(10));
            using var exitCancellation = CancellationTokenSource.CreateLinkedTokenSource(fixture.Token);

            await fixture.Controller.OnTestHostProcessExitedAsync(Process(aborted ? 3 : 17).Object, exitCancellation.Token);

            AssertControllerArtifact(fixture);
            XDocument report = fixture.Report;
            AssertCommonMetadata(fixture, report, TrxBehaviorFixture.Start);
            XElement summary = report.Root!.Element(Ns + "ResultSummary")!;
            Assert.AreEqual("Failed", (string?)summary.Attribute("outcome"));
            AssertCounters(summary, total: 2, executed: 1, passed: 1, failed: 0, timeout: 1, skipped: 0);
            AssertResultMetadata(fixture, report, ["Réussite 東京 😀", "Délai dépassé Ω"], ["Passed", "Failed"], ["Réussite", "Expiration"]);
            Assert.AreEqual("sortie: élève 東京 😀", report.Descendants(Ns + "StdOut").Single().Value);
            Assert.AreEqual("diagnostic: Ω", report.Descendants(Ns + "StdErr").Single().Value);
            XElement runInfo = Assert.ContainsSingle(report.Descendants(Ns + "RunInfo"));
            Assert.AreEqual("Error", (string?)runInfo.Attribute("outcome"));
            Assert.AreEqual(
                aborted ? "Test host process pid: 678 was terminated because the test session was aborted." : "Test host process pid: 678 crashed.",
                runInfo.Element(Ns + "Text")!.Value);
            var display = Assert.ContainsSingle(fixture.Memory.Displays);
            Assert.AreSame<IExtension>(fixture.Controller, display.Producer);
            Assert.AreEqual(exitCancellation.Token, display.Token);
            Assert.AreEqual(
                aborted
                    ? "Test session was aborted; recovered 2 test result(s) from the TRX streaming sidecar (additional results that were in flight at termination time may be missing)."
                    : "Test host crashed; recovered 2 test result(s) from the TRX streaming sidecar (additional results that were in flight at crash time may be missing).",
                Assert.IsInstanceOfType<WarningMessageOutputDeviceData>(display.Data).Message);
            var recoveryError = Assert.ContainsSingle(fixture.Memory.Logs.Where(value => value.Level == LogLevel.Error));
            Assert.AreEqual("Encountered an error while recovering TRX streaming records; salvaged 2 record(s) before stopping.", recoveryError.Message);
            Assert.IsInstanceOfType<EndOfStreamException>(recoveryError.Error);
            Assert.Contains(
                value => value.Level == LogLevel.Information && value.Message == "Recovered 2 test result(s) from TRX streaming sidecar after test host termination.",
                fixture.Memory.Logs);

            XElement collectorElement = Assert.ContainsSingle(report.Descendants(Ns + "Collector"));
            Assert.AreEqual("datacollector://protocol.collector/2.3.4", (string?)collectorElement.Attribute("uri"));
            Assert.AreEqual("Collecteur 東京", (string?)collectorElement.Attribute("collectorDisplayName"));
            Assert.AreEqual("agent", (string?)collectorElement.Attribute("agentName"));
            Assert.AreEqual(Path.Combine("agent", "trace-é-東京.bin"), (string?)Assert.ContainsSingle(collectorElement.Descendants(Ns + "A")).Attribute("href"));
            var copy = Assert.ContainsSingle(fixture.Memory.Copies);
            Assert.AreEqual(attachmentPath, copy.Source);
            Assert.AreEqual(
                Path.Combine(fixture.ResultsDirectory, "zoë_agent_2026-10-30_11_12_23.0000000", "In", "agent", "trace-é-東京.bin"), copy.Destination);
            Assert.AreSequenceEqual(new byte[] { 0, 0xC3, 0xA9, 0xFF, 42 }, fixture.Memory.GetBytes(copy.Destination));
            Assert.AreSequenceEqual(new byte[] { 0, 0xC3, 0xA9, 0xFF, 42 }, fixture.Memory.GetBytes(attachmentPath));
            fixture.Memory.FileSystem.Verify(
                value => value.NewFileStream(sidecar, FileMode.Open, FileAccess.Read, FileShare.ReadWrite), Times.Once);
            Assert.AreSequenceEqual(new[] { sidecar }, fixture.DeleteAttempts);
            Assert.IsFalse(fixture.Memory.ExistingFiles.ContainsKey(sidecar));
            AssertBefore(fixture.Memory.Events, "dispose-read:" + sidecar, "delete:" + sidecar);
            AssertBefore(fixture.Memory.Events, "publish", "delete:" + sidecar);
            fixture.Memory.Capability.Verify(value => value.Enable(), Times.Once);
        }
        finally
        {
            await fixture.CloseAsync();
        }
    }

    [TestMethod]
    public async Task RegisteredLifecycle_CanceledHandshakeCanRetryAndCompleteEmptySession()
    {
        var fixture = new TrxInProcessProtocolFixture(TestContext.CancellationToken);
        try
        {
            await fixture.BindAsync();
            using var rejected = new CancellationTokenSource();
            rejected.Cancel();

            OperationCanceledException cancellation = await Assert.ThrowsExactlyAsync<OperationCanceledException>(
                () => fixture.Lifecycle.BeforeRunAsync(rejected.Token));

            Assert.AreEqual(rejected.Token, cancellation.CancellationToken);
            fixture.Memory.Environment.Verify(value => value.GetEnvironmentVariable("TRXNAMEDPIPENAME"), Times.Never);
            Assert.IsEmpty(fixture.Memory.Files);
            await fixture.ConnectChildAsync();
            await fixture.StartSessionAsync();
            fixture.Memory.Clock.SetupGet(value => value.UtcNow).Returns(TrxBehaviorFixture.Start.AddSeconds(10));
            await fixture.SessionLifetime.OnTestSessionFinishingAsync(fixture.Session);
            await fixture.CloseChildAsync(0);
            Assert.IsEmpty(fixture.Memory.Publications);

            await fixture.Controller.OnTestHostProcessExitedAsync(Process(0).Object, fixture.Token);

            AssertControllerArtifact(fixture);
            XDocument report = fixture.Report;
            AssertCommonMetadata(fixture, report, TrxBehaviorFixture.Start.AddSeconds(1));
            XElement summary = report.Root!.Element(Ns + "ResultSummary")!;
            Assert.AreEqual("Completed", (string?)summary.Attribute("outcome"));
            AssertCounters(summary, total: 0, executed: 0, passed: 0, failed: 0, timeout: 0, skipped: 0);
            Assert.IsTrue(summary.Element(Ns + "Counters")!.Attributes().All(value => value.Value == "0"));
            Assert.IsEmpty(report.Descendants(Ns + "UnitTestResult"));
            Assert.IsEmpty(report.Descendants(Ns + "UnitTest"));
            Assert.IsEmpty(report.Descendants(Ns + "RunInfo"));
            Assert.AreEqual(fixture.ReportPath, Assert.ContainsSingle(fixture.Memory.Files.Keys));
            Assert.IsEmpty(fixture.DeleteAttempts);
            Assert.IsEmpty(fixture.Memory.Displays);
            fixture.Memory.FileSystem.Verify(
                value => value.NewFileStream(It.IsAny<string>(), It.IsAny<FileMode>(), It.IsAny<FileAccess>(), It.IsAny<FileShare>()), Times.Never);
            fixture.Memory.Environment.Verify(value => value.GetEnvironmentVariable("TRXNAMEDPIPENAME"), Times.Once);
            fixture.Memory.Capability.Verify(value => value.Enable(), Times.Once);
        }
        finally
        {
            await fixture.CloseAsync();
        }
    }

    private static TestNodeUpdateMessage Update(string uid, string displayName, TestNodeStateProperty state, string methodName, bool includeOutput = false)
    {
        PropertyBag properties = new(
            state,
            new TestMethodIdentifierProperty("ProtocolSuite", "Protocole", "Tests", methodName, 0, [], "System.Void"),
            new TrxTestDefinitionName("Définition " + methodName),
            new TrxCategoriesProperty(["protocole", "東京"]));
        if (includeOutput)
        {
            properties.Add(new TrxMessagesProperty(
                [new StandardOutputTrxMessage("sortie: élève 東京 😀"), new StandardErrorTrxMessage("diagnostic: Ω")]));
        }

        return new TestNodeUpdateMessage(
            new SessionUid("protocol-session"), new TestNode { Uid = uid, DisplayName = displayName, Properties = properties });
    }

    private static Mock<ITestHostProcessInformation> Process(int exitCode)
    {
        var process = new Mock<ITestHostProcessInformation>(MockBehavior.Strict);
        process.SetupGet(value => value.PID).Returns(678);
        process.SetupGet(value => value.ExitCode).Returns(exitCode);
        return process;
    }

    private static void AssertControllerArtifact(TrxInProcessProtocolFixture fixture)
    {
        var publication = Assert.ContainsSingle(fixture.Memory.Publications);
        Assert.AreSame<IExtension>(fixture.Controller, publication.Producer);
        FileArtifact artifact = Assert.IsInstanceOfType<FileArtifact>(publication.Data);
        Assert.AreEqual(fixture.ReportPath, artifact.FileInfo.FullName);
        Assert.AreEqual("microsoft.testing.trx", artifact.Kind);
        Assert.AreEqual(TrxReport.Resources.ExtensionResources.TrxReportArtifactDisplayName, artifact.DisplayName);
        Assert.AreEqual(TrxReport.Resources.ExtensionResources.TrxReportArtifactDescription, artifact.Description);
    }

    private static void AssertCommonMetadata(TrxInProcessProtocolFixture fixture, XDocument report, DateTimeOffset expectedStart)
    {
        Assert.AreEqual(Ns + "TestRun", report.Root!.Name);
        Assert.AreEqual("a41e114b-2a25-4c12-9395-5def20458c6c", (string?)report.Root.Attribute("id"));
        Assert.AreEqual("zoë@agent 2026-10-30 11:12:23.0000000", (string?)report.Root.Attribute("name"));
        XElement times = report.Root.Element(Ns + "Times")!;
        Assert.AreEqual(expectedStart, (DateTimeOffset)times.Attribute("creation")!);
        Assert.AreEqual(expectedStart, (DateTimeOffset)times.Attribute("queuing")!);
        Assert.AreEqual(expectedStart, (DateTimeOffset)times.Attribute("start")!);
        Assert.AreEqual(TrxBehaviorFixture.Start.AddSeconds(10), (DateTimeOffset)times.Attribute("finish")!);
        Assert.AreEqual(
            "zoë_agent_2026-10-30_11_12_23.0000000",
            (string?)report.Root.Element(Ns + "TestSettings")!.Element(Ns + "Deployment")!.Attribute("runDeploymentRoot"));
        Assert.IsTrue(fixture.Memory.Files[fixture.ReportPath].IsDisposed);
    }

    private static void AssertCounters(XElement summary, int total, int executed, int passed, int failed, int timeout, int skipped)
    {
        XElement counters = summary.Element(Ns + "Counters")!;
        Assert.AreEqual(total, (int)counters.Attribute("total")!);
        Assert.AreEqual(executed, (int)counters.Attribute("executed")!);
        Assert.AreEqual(passed, (int)counters.Attribute("passed")!);
        Assert.AreEqual(failed, (int)counters.Attribute("failed")!);
        Assert.AreEqual(timeout, (int)counters.Attribute("timeout")!);
        Assert.AreEqual(skipped, (int)counters.Attribute("notExecuted")!);
    }

    private static void AssertResultMetadata(TrxInProcessProtocolFixture fixture, XDocument report, string[] displayNames, string[] outcomes, string[] methodNames)
    {
        XElement[] results = [.. report.Descendants(Ns + "UnitTestResult")];
        Assert.AreSequenceEqual(new[] { FirstId, SecondId }, results.Select(value => (string?)value.Attribute("testId")));
        Assert.AreSequenceEqual(displayNames, results.Select(value => (string?)value.Attribute("testName")));
        Assert.AreSequenceEqual(outcomes, results.Select(value => (string?)value.Attribute("outcome")));
        Assert.AreSequenceEqual(new[] { "00:00:00", "00:00:00" }, results.Select(value => (string?)value.Attribute("duration")));
        XElement[] definitions = [.. report.Descendants(Ns + "UnitTest")];
        Assert.AreSequenceEqual(new[] { FirstId, SecondId }, definitions.Select(value => (string?)value.Attribute("id")));
        Assert.AreSequenceEqual(methodNames.Select(value => "Définition " + value), definitions.Select(value => (string?)value.Attribute("name")));
        Assert.AreSequenceEqual(new[] { fixture.ModulePath.ToLowerInvariant(), fixture.ModulePath.ToLowerInvariant() },
            definitions.Select(value => (string?)value.Attribute("storage")));
        XElement[] methods = [.. definitions.Select(value => value.Element(Ns + "TestMethod")!)];
        Assert.AreSequenceEqual(new[] { fixture.ModulePath, fixture.ModulePath }, methods.Select(value => (string?)value.Attribute("codeBase")));
        Assert.AreSequenceEqual(new[] { "executor://adapter.équipe.東京/7.8.9-preview.4", "executor://adapter.équipe.東京/7.8.9-preview.4" },
            methods.Select(value => (string?)value.Attribute("adapterTypeName")));
        Assert.AreSequenceEqual(new[] { "Protocole.Tests", "Protocole.Tests" }, methods.Select(value => (string?)value.Attribute("className")));
        Assert.AreSequenceEqual(methodNames, methods.Select(value => (string?)value.Attribute("name")));
        Assert.AreSequenceEqual(new[] { "protocole", "東京", "protocole", "東京" },
            definitions.SelectMany(value => value.Descendants(Ns + "TestCategoryItem")).Select(value => (string?)value.Attribute("TestCategory")));
        XElement[] entries = [.. report.Descendants(Ns + "TestEntry")];
        Assert.AreSequenceEqual(new[] { FirstId, SecondId }, entries.Select(value => (string?)value.Attribute("testId")));
        Assert.AreSequenceEqual(results.Select(value => (string?)value.Attribute("executionId")), entries.Select(value => (string?)value.Attribute("executionId")));
        Assert.AreSequenceEqual(results.Select(value => (string?)value.Attribute("executionId")), definitions.Select(value => (string?)value.Element(Ns + "Execution")!.Attribute("id")));
    }

    private static void AssertBefore(List<string> events, string earlier, string later)
    {
        Assert.Contains(earlier, events);
        Assert.Contains(later, events);
        Assert.IsLessThan(events.IndexOf(later), events.IndexOf(earlier));
    }
