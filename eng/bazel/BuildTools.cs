using System.Resources;
using System.Text.Json;

if (args.Length == 5 && args[0] == "resx")
{
    GenerateResources(args[1], args[2], args[3], args[4]);
}
else if (args.Length == 5 && args[0] == "xlf")
{
    GenerateTranslations(args[1], args[2], args[3], args[4]);
}
else if (args.Length == 11 && args[0] == "metadata")
{
    GenerateMetadata(args[1], args[2], args[3], args[4], args[5], args[6], args[7], args[8], args[9], args[10]);
}
else if (args.Length == 4 && args[0] == "version")
{
    string version = ReadVersion(args[1], args[2]);
    _ = Version.Parse(version);
    File.WriteAllText(args[3], ExperimentalVersion(version), Encoding.UTF8);
}
else
{
    throw new ArgumentException("Expected resx <input> <type> <resources> <source>, xlf <neutral> <catalog> <culture> <resources>, version <versions> <property> <output>, or metadata <versions> <property> <source> <template> <generated-template> <usings> <version-override> <culture> <assembly-version> <build-status>.");
}

static void GenerateResources(string input, string typeName, string resourcesOutput, string sourceOutput)
{
    int separator = typeName.LastIndexOf('.');
    if (separator < 1 || separator == typeName.Length - 1)
    {
        throw new ArgumentException($"A fully qualified resource type is required: {typeName}");
    }

    SortedDictionary<string, string> entries = ReadResources(input);
    WriteResources(entries, resourcesOutput);

    string className = typeName[(separator + 1)..];
    var source = new StringBuilder();
    source.AppendLine("// <auto-generated/>");
    source.AppendLine("#nullable enable");
    source.AppendLine($"namespace {typeName[..separator]};");
    source.AppendLine($"internal static partial class {className}");
    source.AppendLine("{");
    source.AppendLine($"    internal static global::System.Resources.ResourceManager ResourceManager {{ get; }} = new({Literal(typeName)}, typeof({className}).Assembly);");
    source.AppendLine("    internal static global::System.Globalization.CultureInfo? Culture { get; set; }");
    source.AppendLine("    internal static string GetResourceString(string key) => ResourceManager.GetString(key, Culture)!;");
    foreach (string name in entries.Keys)
    {
        source.AppendLine($"    internal static string @{name} => GetResourceString({Literal(name)});");
    }

    source.AppendLine("}");
    File.WriteAllText(sourceOutput, source.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: true));
}

static SortedDictionary<string, string> ReadResources(string input)
{
    var entries = new SortedDictionary<string, string>(StringComparer.Ordinal);
    XElement root = ReadXml(input).Root ?? throw new InvalidDataException($"Missing RESX root: {input}");
    foreach (XElement item in root.Elements("data"))
    {
        string name = (string?)item.Attribute("name") ?? throw new InvalidDataException($"Missing resource name: {input}");
        string? type = (string?)item.Attribute("type");
        if (item.Attribute("mimetype") is not null || (type is not null && type.Split(',')[0] != "System.String"))
        {
            throw new InvalidDataException($"Only string resources are supported: {input}, {name}");
        }

        if (!Regex.IsMatch(name, @"^[_\p{L}][_\p{L}\p{Nd}]*$", RegexOptions.CultureInvariant))
        {
            throw new InvalidDataException($"Resource name is not a C# identifier: {input}, {name}");
        }

        entries.Add(name, item.Element("value")?.Value ?? throw new InvalidDataException($"Missing resource value: {input}, {name}"));
    }

    return entries;
}

static void WriteResources(SortedDictionary<string, string> entries, string output)
{
    using var writer = new ResourceWriter(output);
    foreach ((string name, string value) in entries)
    {
        writer.AddResource(name, value);
    }
}

static void GenerateTranslations(string neutral, string catalog, string culture, string output)
{
    SortedDictionary<string, string> entries = ReadResources(neutral);
    XNamespace ns = "urn:oasis:names:tc:xliff:document:1.2";
    XDocument document = ReadXml(catalog);
    XElement file = document.Element(ns + "xliff")?.Elements(ns + "file").Single()
        ?? throw new InvalidDataException($"Expected one XLIFF 1.2 file: {catalog}");
    if ((string?)file.Attribute("target-language") != culture)
    {
        throw new InvalidDataException($"Catalog culture does not match {culture}: {catalog}");
    }

    var ids = new HashSet<string>(StringComparer.Ordinal);
    foreach (XElement unit in file.Descendants(ns + "trans-unit"))
    {
        string id = (string?)unit.Attribute("id") ?? throw new InvalidDataException($"Missing translation ID: {catalog}");
        XElement source = unit.Element(ns + "source") ?? throw new InvalidDataException($"Missing translation source: {catalog}, {id}");
        XElement? target = unit.Elements(ns + "target").SingleOrDefault();
        if (!ids.Add(id) || !entries.TryGetValue(id, out string? value) || value != source.Value)
        {
            throw new InvalidDataException($"Duplicate, unknown, or stale translation: {catalog}, {id}");
        }

        if (source.HasElements || target?.HasElements is true)
        {
            throw new InvalidDataException($"Inline XLIFF codes require explicit rendering: {catalog}, {id}");
        }

        // XliffTasks applies every target, independent of state, and uses source when absent.
        entries[id] = target?.Value ?? source.Value;
    }

    WriteResources(entries, output);
}

static XDocument ReadXml(string path)
{
    // Match MSBuild's RESX reader: resource text retains the checkout's line endings.
    using var reader = new XmlTextReader(path)
    {
        Normalization = false,
        DtdProcessing = DtdProcessing.Prohibit,
        XmlResolver = null,
    };
    return XDocument.Load(reader, LoadOptions.PreserveWhitespace);
}

static void GenerateMetadata(string versionsFile, string versionProperty, string output, string template, string templateOutput, string usings, string versionOverride, string culture, string assemblyVersionOverride, string buildStatus)
{
    string version = versionOverride == "-"
        ? ReadVersion(versionsFile, versionProperty)
        : versionOverride;
    Version parsed = Version.Parse(version);
    string fileVersion = $"{parsed.Major}.{parsed.Minor}.{parsed.Build}.0";
    string assemblyVersion = assemblyVersionOverride == "-" ? fileVersion : assemblyVersionOverride;
    string informationalVersion = ExperimentalVersion(version);
    var source = new StringBuilder("// <auto-generated/>\n");
    foreach (string item in usings == "-" ? [] : usings.Split(';', StringSplitOptions.RemoveEmptyEntries))
    {
        source.AppendLine($"global using {item};");
    }

    source.AppendLine($"[assembly: global::System.Reflection.AssemblyVersion({Literal(assemblyVersion)})]");
    source.AppendLine($"[assembly: global::System.Reflection.AssemblyFileVersion({Literal(fileVersion)})]");
    source.AppendLine($"[assembly: global::System.Reflection.AssemblyInformationalVersion({Literal(informationalVersion)})]");
    source.AppendLine("[assembly: global::System.Reflection.AssemblyMetadata(\"TestFx.BuildSystem\", \"Bazel\")]");
    if (culture != "-")
    {
        source.AppendLine($"[assembly: global::System.Reflection.AssemblyCulture({Literal(culture)})]");
    }
    else
    {
        source.AppendLine("[assembly: global::System.Resources.NeutralResourcesLanguage(\"en\")]");
    }

    if (buildStatus != "-")
    {
        string timestamp = File.ReadLines(buildStatus).Single(line => line.StartsWith("BUILD_TIMESTAMP ", StringComparison.Ordinal))["BUILD_TIMESTAMP ".Length..];
        string date = DateTimeOffset.FromUnixTimeSeconds(long.Parse(timestamp, CultureInfo.InvariantCulture)).ToString("yyyy/MM/dd", CultureInfo.InvariantCulture);
        source.AppendLine($"[assembly: global::System.Reflection.AssemblyMetadata(\"Microsoft.Testing.Platform.Application.BuildTimeUTC\", {Literal(date)})]");
    }

    File.WriteAllText(output, source.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: true));

    if (template != "-")
    {
        string content = File.ReadAllText(template);
        if (!content.Contains("${Version}", StringComparison.Ordinal))
        {
            throw new InvalidDataException($"Missing Version substitution in {template}");
        }

        File.WriteAllText(templateOutput, content.Replace("${Version}", informationalVersion, StringComparison.Ordinal), new UTF8Encoding(encoderShouldEmitUTF8Identifier: true));
    }
}

static string ReadVersion(string path, string property)
{
    XElement[] values = ReadXml(path).Descendants(property).ToArray();
    if (values.Length != 1)
    {
        throw new InvalidDataException($"Expected exactly one {property} property in {path}.");
    }

    return values[0].Value;
}

static string ExperimentalVersion(string version) => $"{version}-preview.bazel";

static string Literal(string value) => JsonSerializer.Serialize(value);
